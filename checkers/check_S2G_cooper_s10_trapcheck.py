def h0_P2_monomial_count(d):
    """dim H^0(P^2, O(d)) via LITERAL monomial enumeration: count monomials
    x0^a x1^b x2^c with a+b+c=d, a,b,c>=0 integers. Cross-checked against
    the closed form C(d+2,2) below (h0_P2_binomial). d<0 -> 0 (empty
    enumeration, no special-casing needed)."""
    if d < 0:
        return 0
    count = 0
    for a in range(d + 1):
        for b in range(d - a + 1):
            c = d - a - b
            chk(c >= 0, "monomial enumeration internal error")
            count += 1
    return count


def h0_P2_binomial(d):
    if d < 0:
        return 0
    return int(sp.binomial(d + 2, 2))


