def h0_scroll_aC0_bh(a, b, n):
    """dim H^0(X, a*C0 + b*h) for X = P(O (+) O(n)) over P^2, a>=0, via the
    pushforward decomposition H^0(X,a*C0+b*h) = (+)_{i=0}^{a} H^0(P^2, O(b -
    i*n)) — elementary: Sym^a of a rank-2 bundle O (+) O(-n) (this is the
    convention under which C0, the tautological section of the O-summand,
    has SELF-restriction O_X(C0)|_{C0} = O(-n), matching the classical
    scroll normal-bundle fact used throughout WP-TW1 and re-derived
    independently below in restrict_to_C0) splits as (+)_{i=0}^a O(-i*n)
    (symmetric power of a direct sum of line bundles splits into a direct
    sum of tensor products of the summands — checked by hand for a=1: trivial;
    a=2: Sym^2(L1 (+) L2) = L1^2 (+) L1 L2 (+) L2^2, matching i=0,1,2 exactly
    for L1=O, L2=O(-n))."""
    chk(a >= 0, "h0_scroll_aC0_bh: a must be >= 0 (pushforward decomposition assumes a>=0)")
    total = 0
    for i in range(a + 1):
        total += h0_P2_monomial_count(b - i * n)
    return total


