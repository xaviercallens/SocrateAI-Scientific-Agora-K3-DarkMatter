def tau_mp(re, im2, dps):
    old = mp.mp.dps
    mp.mp.dps = dps + 30
    try:
        return mp.mpc(mp.mpf(re.numerator) / re.denominator,
                      mp.sqrt(mp.mpf(im2.numerator) / im2.denominator))
    finally:
        mp.mp.dps = old


def identify_locus(w_lo, w_hi, loci):
    """1/z against the C1 loci and z = infinity, at both precisions.  Tier B numeric."""
    hits = []
    for name in loci + ["infinity"]:
        target = mp.mpf(0) if name == "infinity" else 1 / mp.mpf(F(name).numerator) * F(name).denominator
        ok = all(abs(w - target) < mp.mpf(10) ** (-(dps - 25)) * (1 + abs(target))
                 for w, dps in ((w_lo, DPS_LO), (w_hi, DPS_HI)))
        if ok:
            hits.append(name)
    return hits[0] if len(hits) == 1 else None


def p2_crosscheck(key, row, t_hi, cert_path=None):
    """Against data/certificates/CM_POINTS_RHO20.json (task P2): at the same z-locus, the same
    (-v^2, div v, D), and the recorded minimal polynomial of t vanishes at the t found here
    (numeric, working precision).  None if the locus is absent from that certificate."""
    cert = json.loads((cert_path or CERTS / "CM_POINTS_RHO20.json").read_text())
    hits = cert["families"][key]["locus_hits"].get(str(row["z_locus"]))
    if not hits:
        return None
    tt = sp.Symbol("t")
    ok = True
    for h in hits:
        coeffs = [int(c) for c in sp.Poly(sp.sympify(h["t_minpoly"]), tt).all_coeffs()]
        val = mp.polyval([mp.mpf(c) for c in coeffs], t_hi)
        ok = ok and abs(val) < mp.mpf(10) ** -(DPS_HI - 30)
        ok = ok and (h["minus_v2"], h["div_v"], h["D"]) == (-row["v2"], row["div_v"], row["D"])
    return bool(ok)


