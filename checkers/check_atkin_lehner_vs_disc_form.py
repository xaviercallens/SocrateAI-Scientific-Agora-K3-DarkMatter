def phi_entries(A, B, C, D, n):
    """UNNORMALISED pullback matrix (divide by det): rows x', y', z' against columns x, y, z."""
    inv_n = sp.Rational(1, 1) / n if isinstance(n, sp.Basic) else F(1, n)
    return [[A * A, -C * C * inv_n, -2 * A * C],
            [-n * B * B, D * D, 2 * n * B * D],
            [-A * B, C * D * inv_n, A * D + B * C]]


def phi(g, n):
    """Normalised phi_g as a 3x3 Fraction matrix.  Refuses on det <= 0."""
    (A, B), (C, D) = g
    det = A * D - B * C
    if det <= 0:
        raise Refused("det_not_positive", f"det = {det}")
    return [[F(e) / det for e in row] for row in phi_entries(A, B, C, D, n)]


def matvec(M, v):
    return tuple(sum(M[i][j] * v[j] for j in range(3)) for i in range(3))


def matmul(X, Y):
    return [[sum(X[i][k] * Y[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def det3(M):
    return (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1])
            - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
            + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0]))


