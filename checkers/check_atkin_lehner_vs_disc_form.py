    res = {}
    for name, rec in mono["generators"].items():
        if not name.startswith("z="):
            continue
        z = name[2:]
        cand = [(rw["v2"], rw["div_v"], rw.get("multiplier_reflection")) for rw in fam["fixed_points"]
                if rw["z_locus"] == z]
        got = (rec.get("v2"), rec.get("div_v"), rec["multiplier_on_A"])
        res[name] = {"monodromy": list(got), "fixed_point_reflections": sorted(set(cand)),
                     "agree": bool(cand) and all(c == got for c in cand)}
        if not res[name]["agree"]:
            raise Refused("monodromy_reflection_disagrees_with_fixed_point", f"{name}: {res[name]}")
    return res


